class TestDatasetSplitter:
    def test_cross_generator_split(self, tmp_path):
        from split_dataset import DatasetSplitter, load_protocol_config

        proto_config = Path("configs/protocols.yaml")
        protocol = load_protocol_config(proto_config, "cross_generator")

        # Create mock metadata CSV with DDPM (train), StyleGAN3 (train), LatDiff (test), Real
        csv_path = tmp_path / "mock_meta.csv"
        rows = [
            {"sample_id": "r1", "label": "0", "generator": "Real", "forgery_type": "REAL", "architecture": "REAL", "source_image_path": ""},
            {"sample_id": "r2", "label": "0", "generator": "Real", "forgery_type": "REAL", "architecture": "REAL", "source_image_path": ""},
            {"sample_id": "f1", "label": "1", "generator": "DDPM", "forgery_type": "EFS", "architecture": "Diffusion", "source_image_path": ""},
            {"sample_id": "f2", "label": "1", "generator": "StyleGAN3", "forgery_type": "EFS", "architecture": "GAN", "source_image_path": ""},
            {"sample_id": "f3", "label": "1", "generator": "LatDiff", "forgery_type": "EFS", "architecture": "Diffusion", "source_image_path": ""},
        ]
        import csv
        with open(csv_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            writer.writeheader()
            writer.writerows(rows)

        splitter = DatasetSplitter(metadata_path=csv_path, protocol=protocol, seed=42)
        splits, all_updated = splitter.split()

        train_gens = {r["generator"] for r in splits["train"] if r["generator"] != "Real"}
        test_gens = {r["generator"] for r in splits["test"] if r["generator"] != "Real"}

        # Disjoint generator check
        assert train_gens.isdisjoint(test_gens)
        assert "DDPM" in train_gens or "StyleGAN3" in train_gens
        assert "LatDiff" in test_gens

    def test_leakage_detection_raises(self, tmp_path):
        from split_dataset import DatasetSplitter

        protocol = {
            "type": "generator_split",
            "train_generators": ["DiffAE"],
            "val_generators": [],
            "test_generators": ["DiffFace"],
            "real_split_ratio": {"train": 1.0, "val": 0.0, "test": 0.0},
        }

        csv_path = tmp_path / "leakage_meta.csv"
        # Two fake images with DIFFERENT generators but SAME source image
        rows = [
            {"sample_id": "s1", "label": "1", "generator": "DiffAE", "source_image_path": "source/shared_face.png"},
            {"sample_id": "s2", "label": "1", "generator": "DiffFace", "source_image_path": "source/shared_face.png"},
        ]
        import csv
        with open(csv_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            writer.writeheader()
            writer.writerows(rows)

        splitter = DatasetSplitter(metadata_path=csv_path, protocol=protocol, seed=42)
        with pytest.raises(RuntimeError, match="Data leakage detected"):
            splitter.split()


