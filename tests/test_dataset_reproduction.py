        (dataset_root / "images" / "EFS" / "DDPM").mkdir(parents=True)
        (dataset_root / "images" / "AM" / "DiffAE").mkdir(parents=True)
        (dataset_root / "images" / "FS" / "DiffFace").mkdir(parents=True)

