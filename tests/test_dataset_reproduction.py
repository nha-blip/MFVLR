class TestMaskGenerator:
    @pytest.fixture
    def mask_gen(self):
        return MaskGenerator(target_size=(224, 224), threshold=0.1)

    def test_real_mask_all_zeros(self, mask_gen):
        fake_img = np.ones((224, 224, 3), dtype=np.uint8) * 128
        mask = mask_gen.generate_mask(label=0, forgery_type="REAL", fake_img=fake_img)
        assert mask.shape == (224, 224)
        assert mask.dtype == np.uint8
        assert np.all(mask == 0)

    def test_efs_mask_all_ones(self, mask_gen):
        fake_img = np.ones((224, 224, 3), dtype=np.uint8) * 128
        mask = mask_gen.generate_mask(label=1, forgery_type="EFS", fake_img=fake_img)
        assert mask.shape == (224, 224)
        assert mask.dtype == np.uint8
        assert np.all(mask == 255)

    def test_am_fs_pixel_difference_threshold(self, mask_gen):
        # Base source: constant gray 100
        source_img = np.full((224, 224, 3), 100, dtype=np.uint8)

        # Fake image:
        # Left half: diff = 10 (10/255 = ~0.039 <= 0.1 -> mask should be 0)
        # Right half: diff = 40 (40/255 = ~0.157 > 0.1 -> mask should be 255)
        fake_img = np.full((224, 224, 3), 100, dtype=np.uint8)
        fake_img[:, :112, :] = 110  # diff = 10
        fake_img[:, 112:, :] = 140  # diff = 40

        mask = mask_gen.generate_mask(
            label=1,
            forgery_type="AM",
            fake_img=fake_img,
            source_img=source_img,
        )

        assert mask.shape == (224, 224)
        assert mask.dtype == np.uint8
        # Left half should be 0
        assert np.all(mask[:, :112] == 0)
        # Right half should be 255
        assert np.all(mask[:, 112:] == 255)

    def test_am_missing_source_raises(self, mask_gen):
        fake_img = np.full((224, 224, 3), 128, dtype=np.uint8)
        with pytest.raises(ValueError, match="Source image is required"):
            mask_gen.generate_mask(label=1, forgery_type="AM", fake_img=fake_img, source_img=None)

    def test_fs_missing_source_raises(self, mask_gen):
        fake_img = np.full((224, 224, 3), 128, dtype=np.uint8)
        with pytest.raises(ValueError, match="Source image is required"):
            mask_gen.generate_mask(label=1, forgery_type="FS", fake_img=fake_img, source_img=None)


