"""Fine-grained Text Generator (FTG) for hierarchical prompts (L1 to L4).

PAPER_SPECIFIED:
- Level 1 (L1) - Authenticity:
    Real: "A photo of a real face"
    Fake: "A photo of a fake face"
- Level 2 (L2) - Manipulation category:
    Real: "A photo of a real face"
    Entire Face Synthesis (EFS): "A photo of an entire synthesized face"
    Face Swapping (FS): "A photo of an identity swapped face"
    Attribute Manipulation (AM): "A photo of an attribute manipulated face"
- Level 3 (L3) - Generative source family:
    Real: "A photo of a real face"
    Diffusion: "A photo generated by the diffusion-based model"
    GAN: "A photo generated by the GAN-based model"
- Level 4 (L4) - Specific generator:
    Real: "A photo of a real face"
    Fake: "The source generative model of this photo is [generator]"
"""

from typing import Dict, List, Optional, Union


# Known generators and their category mappings from the paper (Section III-D, Fig. 6, GenFace benchmark)
GENERATOR_TO_FAMILY = {
    # Diffusion models
    "DDPM": "diffusion",
    "LatDiff": "diffusion",
    "LatentDiffusion": "diffusion",
    "CollDiff": "diffusion",
    "CollaborativeDiffusion": "diffusion",
    "DiffFace": "diffusion",
    "Diffae": "diffusion",
    # GAN models
    "StyleGAN3": "gan",
    "FSLSD": "gan",
    "FaceSwapper": "gan",
    "LatTrans": "gan",
    "LatentTransformer": "gan",
    "IA-FaceS": "gan",
    "IAFaces": "gan",
}

GENERATOR_TO_CATEGORY = {
    # Entire Face Synthesis (EFS)
    "DDPM": "EFS",
    "LatDiff": "EFS",
    "LatentDiffusion": "EFS",
    "CollDiff": "EFS",
    "CollaborativeDiffusion": "EFS",
    "StyleGAN3": "EFS",
    # Face Swapping (FS)
    "DiffFace": "FS",
    "FSLSD": "FS",
    "FaceSwapper": "FS",
    # Attribute Manipulation (AM)
    "Diffae": "AM",
    "LatTrans": "AM",
    "LatentTransformer": "AM",
    "IA-FaceS": "AM",
    "IAFaces": "AM",
}


class FineGrainedTextGenerator:
    """Generate hierarchical text prompts (L1 to L4) for face images."""

    def __init__(self, packing_strategy: str = "4x77_concat"):
        """
        Args:
            packing_strategy: Strategy for formatting prompts.
                # ASSUMPTION_FROM_PAPER_GAP:
                # Paper illustrates L1-L4 lines and uses a single token sequence n=308.
                # '4x77_concat' maintains each level as a distinct prompt line.
        """
        self.packing_strategy = packing_strategy

    def generate_prompts(
        self,
        is_fake: bool,
        forgery_type: Optional[str] = None,
        generator: Optional[str] = None,
        family: Optional[str] = None,
    ) -> Dict[str, str]:
        """Generate individual L1-L4 prompts.

        Args:
            is_fake: Whether the face is fake/manipulated.
            forgery_type: One of 'EFS', 'FS', 'AM', or None.
            generator: Generator name (e.g. 'DDPM', 'DiffFace', 'StyleGAN3').
            family: One of 'diffusion', 'gan', or None.

        Returns:
            Dictionary with keys 'L1', 'L2', 'L3', 'L4', and 'full_prompt'.
        """
        if not is_fake:
            l1 = "A photo of a real face"
            l2 = "A photo of a real face"
            l3 = "A photo of a real face"
            l4 = "A photo of a real face"
            return {
                "L1": l1,
                "L2": l2,
                "L3": l3,
                "L4": l4,
                "full_prompt": f"{l1}\n{l2}\n{l3}\n{l4}",
            }

        # L1 Authenticity
        l1 = "A photo of a fake face"

        # L2 Manipulation category
        if forgery_type is None and generator is not None:
            forgery_type = GENERATOR_TO_CATEGORY.get(generator, "EFS")

        if forgery_type == "EFS":
            l2 = "A photo of an entire synthesized face"
        elif forgery_type == "FS":
            l2 = "A photo of an identity swapped face"
        elif forgery_type == "AM":
            l2 = "A photo of an attribute manipulated face"
        else:
            l2 = "A photo of a fake face"

        # L3 Generative source family
        if family is None and generator is not None:
            family = GENERATOR_TO_FAMILY.get(generator, "diffusion")

        if family == "diffusion":
            l3 = "A photo generated by the diffusion-based model"
        elif family == "gan":
            l3 = "A photo generated by the GAN-based model"
        else:
            l3 = "A photo generated by the generative model"

        # L4 Specific generator
        gen_name = generator if generator is not None else "generative model"
        l4 = f"The source generative model of this photo is {gen_name}"

        return {
            "L1": l1,
            "L2": l2,
            "L3": l3,
            "L4": l4,
            "full_prompt": f"{l1}\n{l2}\n{l3}\n{l4}",
        }
