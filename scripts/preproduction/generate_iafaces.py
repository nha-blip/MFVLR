GENERATOR = "IAFaces"
FORGERY_TYPE = "AM"
ARCHITECTURE = "GAN"
CATEGORY = "AM"
REPO = "https://github.com/CMACH508/IA-FaceS.git"
COMMIT = "50e18fc091f03f5ce6bbd377b7f58cb2e93b4dd6"
CHECKPOINT = "checkpoints/AM/IAFaces/iafaces-celebahq-256.pth"
