def patched_load(name, sources, *args, **kwargs):
    cuda_flags = kwargs.get("extra_cuda_cflags", [])
    for f in ["-allow-unsupported-compiler", "-D_ALLOW_COMPILER_AND_STL_VERSION_MISMATCH"]:
        if f not in cuda_flags:
            cuda_flags.append(f)
    kwargs["extra_cuda_cflags"] = cuda_flags

    c_flags = kwargs.get("extra_cflags", [])
    if "/D_ALLOW_COMPILER_AND_STL_VERSION_MISMATCH" not in c_flags:
        c_flags.append("/D_ALLOW_COMPILER_AND_STL_VERSION_MISMATCH")
    kwargs["extra_cflags"] = c_flags

    short_sources = [os.path.join(get_short_path(os.path.dirname(s)), os.path.basename(s)) for s in sources]
    return orig_load(name, short_sources, *args, **kwargs)

